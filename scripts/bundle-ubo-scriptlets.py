#!/usr/bin/env python3
"""Bundles uBlock Origin's scriptlets into one plain script for Brújula.

uBlock Origin writes its scriptlets as ES modules (src/js/resources/*.js). A browser user
script cannot import modules, so this walks the imports from `scriptlets.js`, puts every module
in dependency order, drops the `import`/`export` keywords and wraps the result so nothing leaks
into the page's global scope. The output is committed, so building Brújula needs no network.

    scripts/bundle-ubo-scriptlets.py [commit] > crates/brujula/resources/ubo-scriptlets.js.txt

uBlock Origin is GPL-3.0-or-later, like Brújula.
"""

import re
import sys
import urllib.request

# A tagged release of gorhill/uBlock; change it here to update.
DEFAULT_COMMIT = "aa9236cb351e369cbb68113dbe8175b87f3cd134"  # 1.76.0
BASE = "https://raw.githubusercontent.com/gorhill/uBlock/{commit}/src/js/{name}"

# `import { a, b as c } from './x.js';`, also over several lines, and `import './x.js';`
IMPORT = re.compile(
    r"^import(?P<what>[^'\";]*)['\"](?P<path>\.{1,2}/[^'\"]+)['\"];?[ \t]*$",
    re.M,
)


def fetch(commit, name):
    with urllib.request.urlopen(BASE.format(commit=commit, name=name), timeout=60) as r:
        return r.read().decode("utf-8")


def resolve(base, path):
    """`path` as written in a module that lives at `base`, as a path under src/js."""
    parts = base.split("/")[:-1]
    for piece in path.split("/"):
        if piece == "..":
            parts.pop()
        elif piece != ".":
            parts.append(piece)
    return "/".join(parts)


def strip(source, base):
    """Source without import statements and export keywords, plus the modules it imports."""
    deps, aliases = [], []

    def drop(match):
        deps.append(resolve(base, match.group("path")))
        what = match.group("what").strip().removesuffix("from").strip(" {}\t\r\n")
        for spec in what.split(","):
            words = spec.split()
            if len(words) == 3 and words[1] == "as":
                aliases.append((words[0], words[2]))
        return ""

    source = IMPORT.sub(drop, source)
    source = re.sub(r"^export[ \t]*\{[^}]*\}(?:[ \t]*from[ \t]*['\"][^'\"]+['\"])?;?[ \t]*$", "", source, flags=re.M)
    source = re.sub(r"^export\s+default\s+", "", source, flags=re.M)
    source = re.sub(r"^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)", "", source, flags=re.M)
    # `import { a as b }` becomes a constant, after the module that defines `a`. Everything is
    # one scope here, so the module's own `const a = b;` re-declaration is dropped.
    for a, b in aliases:
        source = re.sub(rf"^const {a} = {b};[ \t]*$", "", source, flags=re.M)
    source = "".join(f"const {b} = {a};\n" for a, b in aliases) + source
    return source, deps


def main():
    commit = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_COMMIT
    order, seen = [], set()

    def visit(name):
        if name in seen:
            return
        seen.add(name)
        source, deps = strip(fetch(commit, name), name)
        for dep in deps:
            visit(dep)
        order.append((name, source))

    visit("resources/scriptlets.js")
    print(f"// uBlock Origin scriptlets, bundled from gorhill/uBlock@{commit}")
    print("// GPL-3.0-or-later. Generated by scripts/bundle-ubo-scriptlets.py: do not edit.")
    print("(function() {")
    print("'use strict';")
    print("const scriptletGlobals = {};")
    for name, source in order:
        print(f"\n// ---- {name}")
        print(source)
    print("\nreturn registeredScriptlets;")
    print("})()")


main()
